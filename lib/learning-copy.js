export function learningError(error, copy, file = false) {
  const code = error?.code;
  if (code === "VERIFICATION_FAILED") return copy.verificationFailed;
  if (code === "VERIFICATION_RATE_LIMITED" || error?.status === 429)
    return copy.rateLimited;
  if (code === "TRAINING_RECOVERY_UNAVAILABLE") return copy.recoveryUnavailable;
  if (
    code === "TRAINING_ACCESS_REQUIRED" ||
    (error?.status === 403 && code !== "PERMISSION_DENIED")
  )
    return copy.accessRequired;
  if (code === "PERMISSION_DENIED") return copy.requestDenied;
  if (code === "TRAINING_LINK_UNSUPPORTED") return copy.linkUnsupported;
  if (code === "ACCESS_EXPIRED") return copy.expiredAccess;
  if (code === "NO_RESULT" || error?.status === 404) return copy.unavailable;
  if (error?.status === 401) return copy.sessionExpired;
  if (code === "INVALID_RESPONSE") return copy.invalidResponse;
  if (file && error?.status === 503) return copy.storageError;
  return error?.status ? copy.temporary : copy.offline;
}
