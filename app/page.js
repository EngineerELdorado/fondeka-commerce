const languageNames = {
    en: 'English',
    fr: 'Français',
};

function normalizeLocale(value) {
    return String(value || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

async function resolveLocale(searchParams) {
    const params = await searchParams;
    return normalizeLocale(params?.lang);
}

function pathForLocale(locale) {
    return locale === 'fr' ? '/?lang=fr' : '/';
}

function contentFor(locale) {
    return landingCopy[locale] || landingCopy.en;
}

function buildJsonLd(copy) {
    return {
        '@context': 'https://schema.org',
        '@type': 'SoftwareApplication',
        name: 'Fondeka Commerce',
        applicationCategory: 'BusinessApplication',
        operatingSystem: 'Web',
        url: 'https://commerce.fondeka.com',
        description: copy.seo.description,
        offers: {
            '@type': 'Offer',
            category: 'SaaS ecommerce, POS, and payment platform',
        },
        audience: {
            '@type': 'BusinessAudience',
            audienceType: 'African merchants, retailers, digital sellers, and small businesses',
        },
        publisher: {
            '@type': 'Organization',
            name: 'Fondeka',
            url: 'https://fondeka.com',
        },
    };
}

export async function generateMetadata({ searchParams }) {
    const locale = await resolveLocale(searchParams);
    const copy = contentFor(locale);

    return {
        title: {
            absolute: copy.seo.title,
        },
        description: copy.seo.description,
        alternates: {
            canonical: pathForLocale(locale),
            languages: {
                en: '/',
                fr: '/?lang=fr',
            },
        },
        openGraph: {
            title: copy.seo.title,
            description: copy.seo.ogDescription,
            url: `https://commerce.fondeka.com${pathForLocale(locale)}`,
            siteName: 'Fondeka Commerce',
            type: 'website',
            locale: locale === 'fr' ? 'fr_FR' : 'en_US',
            alternateLocale: locale === 'fr' ? ['en_US'] : ['fr_FR'],
        },
        twitter: {
            card: 'summary_large_image',
            title: copy.seo.title,
            description: copy.seo.ogDescription,
        },
    };
}

